NSString *NLFormatDistance(double meters) {
    if (meters >= 1000.0) {
        return [NSString stringWithFormat:@"%.1f %@", meters / 1000.0, NLString(@"UNIT_KM", @"км")];
    }
    return [NSString stringWithFormat:@"%d %@", (int)round(meters), NLString(@"UNIT_M", @"м")];
}

NSString *NLFormatDuration(NSTimeInterval seconds) {
    int mins = (int)ceil(seconds / 60.0);
    int hours = mins / 60;
    int remMins = mins % 60;
    if (hours > 0) {
        return [NSString stringWithFormat:@"%d %@ %02d %@", hours, NLString(@"UNIT_H", @"ч"), remMins, NLString(@"UNIT_MIN", @"мин")];
    }
    return [NSString stringWithFormat:@"%d %@", mins, NLString(@"UNIT_MIN", @"мин")];
}
